def fmt_bn(x):
    return f'{x:,.1f}억원' if x < 1000 else f'{x/1000:,.2f}조원'

def pct_change(a,b):
    return (b/a-1)*100 if a else None

def insight_box(title, lines):
    st.markdown(f'### {title}')
    for line in lines:
        st.markdown(f'- {line}')

def analysis_guide(why, how, conclusions):
    # 각 분석 탭 최상단에 분석 목적 → 방법 → 상세 결론을 고정 표시합니다.
    st.markdown('### 1. 왜 분석하나요?')
    st.info(why)
    st.markdown('### 2. 어떻게 분석하나요?')
    st.info(how)
    st.markdown('### 3. 이 탭에서 얻을 수 있는 결론은 무엇인가요?')
    with st.container(border=True):
        for i, item in enumerate(conclusions, 1):
            st.markdown(f'**결론 {i}.** {item}')
    st.divider()

